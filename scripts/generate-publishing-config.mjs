#!/usr/bin/env node
// Bakes the desktop publishing config into a generated module at build time. The file is gitignored:
// a release job sets REUPMATIC_META_APP_ID, REUPMATIC_META_BROKER_URL and REUPMATIC_GOOGLE_CLIENT_ID
// and runs the build; a dev checkout with none ends up with `null` and falls back to the environment
// at runtime.
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_TARGET = path.join(
  root,
  'app',
  'electron',
  'features',
  'publishing',
  'config.generated.ts',
);

function readMeta(env) {
  const metaAppId = env.REUPMATIC_META_APP_ID?.trim();
  const broker = env.REUPMATIC_META_BROKER_URL?.trim();
  if (!metaAppId || !broker) return null;
  try {
    const url = new URL(broker);
    if (url.protocol !== 'https:') return null;
  } catch {
    return null;
  }
  return { metaAppId, brokerUrl: broker.replace(/\/$/, '') };
}

/** Pure parse so the script and its test share one definition of a valid build config. */
export function publishingConfigFromEnv(env = process.env) {
  const meta = readMeta(env);
  const googleClientId = env.REUPMATIC_GOOGLE_CLIENT_ID?.trim();
  if (!meta && !googleClientId) return null;
  return {
    ...(meta ? { metaAppId: meta.metaAppId, brokerUrl: meta.brokerUrl } : {}),
    ...(googleClientId ? { googleClientId } : {}),
  };
}

export function renderPublishingConfigModule(config) {
  const fields = config
    ? Object.entries(config)
        .map(([key, value]) => `${key}: ${JSON.stringify(value)}`)
        .join(', ')
    : '';
  const literal = config ? `{ ${fields} }` : 'null';
  return `// GENERATED by scripts/generate-publishing-config.mjs from the build environment.
// Do not edit or commit; regenerate with \`pnpm run config:generate\`.
import type { PublishingConfig } from './config.js';

export const GENERATED_PUBLISHING_CONFIG: PublishingConfig | null = ${literal};
`;
}

async function main() {
  const outIndex = process.argv.indexOf('--out');
  const target =
    outIndex >= 0 && process.argv[outIndex + 1]
      ? path.resolve(process.argv[outIndex + 1])
      : DEFAULT_TARGET;
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, renderPublishingConfigModule(publishingConfigFromEnv()), 'utf-8');
  console.log(`Generated ${path.relative(root, target)} from the build environment.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
